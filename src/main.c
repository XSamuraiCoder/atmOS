/*
 * atmOS - a desktop-style shell for the TI-84 Plus CE (step 1 + basic step 2)
 *  - gradient wallpaper, menu bar (battery + time), floating dock holding every app
 *  - arrows move a pointer (hold to speed up), Enter or 2nd clicks
 *  - dock entries (Files, Notes, Settings) open an app window; Clear closes the
 *    window, then exits
 *  - dock icons come from src/gfx (convimg) when present, letter squares otherwise
 *
 * Everything on screen is built from one entry table, so customization
 * (moving icons, pinning, themes) can be added later without restructuring.
 *
 * step 3: Files lists programs, AppVars, and installed Flash Apps. The Flash
 * App build can launch Flash Apps through a TI OS handoff, but cannot run
 * calculator programs through os_RunPrgm.
 *
 * step 4: mods. AppVars whose data starts with "atmOS mod: " are loaded at
 * startup (mods.c); each may register apps (dock icons + windows) and theme
 * presets. Registered apps open like the built-ins through the APP_MOD
 * dispatch below.
 */


/* ---------- helpers ---------- */
static uint8_t lerp8(uint8_t a, uint8_t b, int i, int n)
{
    return (uint8_t)(a + ((int)b - (int)a) * i / (n - 1));
}

static void set_pal(int idx, rgb_t c)
{
    gfx_palette[idx] = gfx_RGBTo1555(c.r, c.g, c.b);
}

static void setup_palette(void)
{
    const theme_t *th = settings_theme();
    int i;
    for (i = 0; i < GRAD_STEPS; i++) {
        rgb_t c = {
            lerp8(th->top.r, th->bottom.r, i, GRAD_STEPS),
            lerp8(th->top.g, th->bottom.g, i, GRAD_STEPS),
            lerp8(th->top.b, th->bottom.b, i, GRAD_STEPS)
        };
        set_pal(PAL_GRAD0 + i, c);
    }
    set_pal(PAL_BAR, th->bar);
    set_pal(PAL_BAR_LINE, th->bar_line);
    set_pal(PAL_DOCK, th->dock);
    set_pal(PAL_TEXT, (rgb_t){ 30, 30, 34 });
    set_pal(PAL_LABEL, (rgb_t){ 255, 255, 255 });
    set_pal(PAL_ACCENT, th->accent);
    for (i = 0; i < PAL_ICON_COUNT; i++)
        set_pal(PAL_ICON0 + i, icon_colors[i]);
}

static void begin_graphics(void)
{
    gfx_Begin();
#ifdef HAVE_ICONS
    gfx_SetPalette(global_palette, sizeof_global_palette, 0);
    gfx_SetTransparentColor(255);
#endif
    setup_palette();
    /* gfx_Begin leaves the OS's 16bpp image in VRAM; shown as 8bpp it is
     * garbage (purple) until the first frame. Paint it before it is seen. */
    gfx_FillScreen(PAL_GRAD0);
    gfx_SetDrawBuffer();
    gfx_SetTextConfig(gfx_text_clip);
    ui_text_apply();                 /* font chosen in Settings (gfx_Begin resets it) */
}

/* gfx_End switches the LCD to 16bpp while VRAM still holds 8bpp indices,
 * which flashes purple noise. Zero VRAM (black in 16bpp) first. */
/* SHLSET / SHNOTES are NOT written here anymore. File and flash work must never run
 * while the shell is on its own malloc'd stack (the invariant in settings.c's
 * store_prefs): flushing inside end_graphics() reset the calculator at exit
 * whenever a settings change was still pending - e.g. a mod theme picked in
 * Settings (or applied by a mod) wrote and archived SHLSET from the shell stack.
 * shell_flush() now runs in main(), after the shell has returned to the OS stack. */
static void end_graphics(void)
{
    memset(gfx_vram, 0, GFX_LCD_WIDTH * GFX_LCD_HEIGHT * 2);
    gfx_End();
}

/* Write + archive the stored settings. Call only on the OS stack: after
 * shell_main() has returned (both builds below), never from inside it. */
static void shell_flush(void)
{
    notes_flush();          /* write + archive SHNOTES */
    settings_flush();       /* write + archive SHLSET */
}

static void fill_round_rect(int x, int y, int w, int h, int r)
{
    gfx_FillRectangle(x + r, y, w - 2 * r, h);
    gfx_FillRectangle(x, y + r, w, h - 2 * r);
    gfx_FillCircle(x + r,         y + r,         r);
    gfx_FillCircle(x + w - r - 1, y + r,         r);
    gfx_FillCircle(x + r,         y + h - r - 1, r);
    gfx_FillCircle(x + w - r - 1, y + h - r - 1, r);
}

/* ---------- drawing ---------- */
static void draw_wallpaper(void)
{
    int i, band = GFX_LCD_HEIGHT / GRAD_STEPS;
    for (i = 0; i < GRAD_STEPS; i++) {
        gfx_SetColor(PAL_GRAD0 + i);
        gfx_FillRectangle(0, i * band, GFX_LCD_WIDTH,
                                 (i == GRAD_STEPS - 1) ? GFX_LCD_HEIGHT - i * band : band);
    }
}

/* menu bar: title on the left, battery and time on the right.
 * boot_GetTime/boot_GetBatteryStatus call into the OS, so they are polled only about
 * once a second (BAR_POLL_FRAMES) and drawing uses the cached values. */
#define BAR_POLL_FRAMES 60

static uint8_t bar_h, bar_min = 255, bar_batt = 255;
static bool    bar_chg = false;
static int     bar_poll = 0;

static bool bar_tick(void)           /* true when the bar needs a redraw */
{
    uint8_t s, m, h, b;
    bool chg;

    if (bar_poll > 0) { bar_poll--; return false; }
    bar_poll = BAR_POLL_FRAMES;

    b = boot_GetBatteryStatus();
    chg = boot_BatteryCharging();
    boot_GetTime(&s, &m, &h);

    if (m != bar_min || h != bar_h || b != bar_batt || chg != bar_chg) {
        bar_min = m; bar_h = h; bar_batt = b; bar_chg = chg;
        return true;
    }
    return false;
}

static uintptr_t min_sp = (uintptr_t)-1;
static bool own_stack;                 /* NEW: true once the shell runs on its malloc'd stack */

void shell_note_stack(void)
{
    volatile uint8_t probe;
    uintptr_t sp = (uintptr_t)&probe;
    if (sp < min_sp) min_sp = sp;
}

#ifdef SHELL_DEBUG_STACK
static void draw_stack_debug(void)
{
    static const char hex[] = "0123456789ABCDEF";
    char s[12] = "SP ";
    int i;
    for (i = 0; i < 6; i++)
        s[3 + i] = hex[(min_sp >> (20 - 4 * i)) & 15];
    s[9] = 0;
    ui_print(s, 118, 3);
    if (!own_stack)
        ui_print("OSSTK", 184, 3);     /* NEW: no stack of our own: the OS stack is in use */
}
#endif

static void draw_menu_bar(void)
{
    char t[9];
    int i, tw, bx;

    if (settings_clock_24h()) {
        t[0] = (char)('0' + (bar_h / 10) % 10); t[1] = (char)('0' + bar_h % 10); t[2] = ':';
        t[3] = (char)('0' + (bar_min / 10) % 10); t[4] = (char)('0' + bar_min % 10); t[5] = 0;
    } else {
        uint8_t h12 = bar_h % 12;
        int k = 0;
        if (h12 == 0) h12 = 12;
        if (h12 >= 10) t[k++] = '1';
        t[k++] = (char)('0' + h12 % 10);
        t[k++] = ':';
        t[k++] = (char)('0' + (bar_min / 10) % 10);
        t[k++] = (char)('0' + bar_min % 10);
        t[k++] = ' ';
        t[k++] = bar_h >= 12 ? 'P' : 'A';
        t[k++] = 'M';
        t[k] = 0;
    }

    gfx_SetColor(PAL_BAR);
    gfx_FillRectangle(0, 0, GFX_LCD_WIDTH, MENU_H);
    gfx_SetColor(PAL_BAR_LINE);
    gfx_HorizLine(0, MENU_H, GFX_LCD_WIDTH);

    ui_text_color(PAL_TEXT);
    gfx_SetTextBGColor(PAL_BAR);
    gfx_SetTextTransparentColor(PAL_BAR);
    ui_print(status, 6, 3);
#ifdef SHELL_DEBUG_STACK
    draw_stack_debug();
#endif

    tw = ui_text_width(t);
    ui_print(t, GFX_LCD_WIDTH - 6 - tw, 3);

    if (!settings_show_battery()) return;     /* Settings > Taskbar */

    /* battery: 4 segments, blue while charging, red when nearly empty */
    bx = GFX_LCD_WIDTH - 6 - tw - 8 - 20;
    gfx_SetColor(PAL_TEXT);
    gfx_FillRectangle(bx, 3, 18, 8);
    gfx_FillRectangle(bx + 18, 5, 2, 4);
    gfx_SetColor(PAL_BAR);
    gfx_FillRectangle(bx + 1, 4, 16, 6);
    gfx_SetColor(bar_chg ? PAL_ACCENT : (bar_batt <= 1 ? PAL_ICON0 : PAL_ICON0 + 2));
    for (i = 0; i < bar_batt && i < 4; i++)
        gfx_FillRectangle(bx + 2 + i * 4, 5, 3, 4);
}

/* ---------- window / app framework ---------- */
#define WIN_X    8
#define WIN_Y    MENU_H
#define WIN_W    (GFX_LCD_WIDTH - 2 * WIN_X)
#define WIN_H    (DOCK_Y - WIN_Y)
#define TITLE_H  16


typedef struct {
    const char *title;
    void (*draw)(int x, int y);    /* x,y = top-left of the content area */
    void (*click)(int x, int y);   /* x,y relative to the content area */
    bool (*tick)(void);            /* periodic work; true = redraw */
    bool (*hover)(int x, int y);   /* pointer moved over the content area */
    bool (*keys)(void);            /* arrows; true = app used them, pointer stays */
    bool (*press)(void);           /* Enter/2nd; true = app handled it */
    void (*draw_region)(int x, int y, int x0, int y0, int x1, int y1);
    /* optional: screen rectangles (x0,y0,x1,y1) that changed since the last call; the shell
     * repaints only those. Returns the count, or -1 for "repaint the whole window". */
    int  (*dirty)(int x, int y, int r[][4], int max);
} app_t;

static int open_app = -1;          /* index into apps[], or -1 = no window */
static int open_entry = -1;        /* dock entry that opened it */
static int open_mod = -1;          /* index into mods_app() while open_app == APP_MOD */

static void text_color(uint8_t fg)
{
    ui_text_color(fg);
    gfx_SetTextBGColor(255);
    gfx_SetTextTransparentColor(255);
}


static bool in_window(void)
{
    return open_app >= 0 &&
           cur_x >= WIN_X && cur_x < WIN_X + WIN_W &&
           cur_y >= WIN_Y && cur_y < WIN_Y + WIN_H;
}

static void close_window(void)
{
    open_app = -1;
    open_entry = -1;
    open_mod = -1;
    strcpy(status, OS_NAME);
}

/* ---------- dock entries for mod-registered apps ---------- */
static void sync_dock_mods(void)
{
    int i, n = mods_app_count();

    for (i = 0; i < n && entry_count < MAX_DOCK_ENTRIES; i++) {
        const atmos_app_t *a = mods_app(i);
        entry_t *e = &entries[entry_count++];

        strncpy(e->name, a->title, 8);
        e->name[8] = 0;
        e->color = a->color < 8 ? a->color : 7;
        e->flags = 0;
        e->app = APP_MOD;
        e->type = 0;
        e->program_kind = 0;
        e->mod = (int8_t)i;
    }
}

static void sync_dock_pins(void)
{
    files_pin_t pins[FILES_MAX_PINS];
    size_t count = files_get_pins(pins, FILES_MAX_PINS);
    size_t i;

    entry_count = BUILTIN_ENTRY_COUNT;
    for (i = 0; i < count && i < FILES_MAX_PINS; i++) {
        entry_t *entry = &entries[entry_count++];
        dock_pin_sprites[i][0] = 16;
        dock_pin_sprites[i][1] = 16;
        memcpy(entry->name, pins[i].name, sizeof(entry->name));
        entry->name[sizeof(entry->name) - 1] = 0;
        entry->color = pins[i].type == FILES_TYPE_APP
            ? 4 : pins[i].type == OS_TYPE_PROT_PRGM ? 6 : 3;
        entry->flags = 0;
        entry->app = -1;
        entry->type = pins[i].type;
        entry->program_kind = pins[i].program_kind;
        entry->mod = -1;
        /* Skip Flash App pin icons at sync time: flash_apps_find_app hits
         * OS-version-specific entry points; a mismatch in CEmu can NMI-reset
         * before the shell draws a frame. Program pins still get icons. */
        if (pins[i].type == FILES_TYPE_APP)
            dock_pin_has_icon[i] = false;
        else
            dock_pin_has_icon[i] = files_load_pin_icon(
                &pins[i], dock_pin_sprites[i] + 2);
    }
    for (; i < FILES_MAX_PINS; i++)
        dock_pin_has_icon[i] = false;

    sync_dock_mods();      /* mods stay after the built-ins and pins */
}

static void launch(const entry_t *e)
{
    /* A NOTES program on the calculator replaces the built-in Notes UI. */
    if (e == &entries[ENTRY_NOTES]) {
        const char *prgm;
        uint8_t var_type, program_kind;
        if (notes_find_program(&prgm, &var_type, &program_kind)) {
#ifdef SHELL_FLASH_APP
            end_graphics();
            asm_runProgram_run(prgm, var_type, program_kind,
                               program_runner_preferences);
#else
            run_program(prgm);
            return;
#endif
        }
    }

    if (e->app >= 0) {
        const atmos_app_t *a;
        open_app = e->app;
        open_entry = (int)(e - entries);
        strcpy(status, e->name);
        if (e->app == APP_FILES) files_open();   /* rescan the VAT on open */
        if (e->app == APP_NOTES) notes_open();
        if (e->app == APP_SETTINGS) settings_open();
        if (e->app == APP_MOD) {                 /* a mod-registered app */
            open_mod = e->mod;
            a = mods_app(open_mod);
            if (a && a->open) a->open();
        }
        return;
    }

    if (e->type == FILES_TYPE_APP) {
        end_graphics();
        void *header = flash_apps_find_app(e->name);
        if (header) flash_apps_launch(header);
        begin_graphics();
        strcpy(status, "APP NOT FOUND");
        return;
    }
#ifdef SHELL_FLASH_APP
    end_graphics();
    /* the kind saved in a pin can be stale; look at the program again */
    asm_runProgram_run(e->name, e->type, files_program_kind(e->name, e->type),
                       program_runner_preferences);
#else
    run_program(e->name);
#endif
}

static void do_click(int hover)
{
    if (in_window()) {
        int dx = cur_x - (WIN_X + 10), dy = cur_y - (WIN_Y + 8);
        if (dx * dx + dy * dy <= 36) {
            close_window();                              /* red close dot */
        } else if (cur_y >= WIN_Y + TITLE_H && apps[open_app].click) {
            apps[open_app].click(cur_x - WIN_X, cur_y - (WIN_Y + TITLE_H));
        }
    } else if (hover >= 0) {
        launch(&entries[hover]);
    }
}

/* ---------- dock: positions and hit testing ---------- */
static int dock_width(int n)
{
    return n * DOCK_ITEM + (n + 1) * DOCK_GAP;
}

static void dock_item_pos(int slot, int *x, int *y)
{
    int x0 = (GFX_LCD_WIDTH - dock_width(entry_count)) / 2;
    *x = x0 + DOCK_GAP + slot * (DOCK_ITEM + DOCK_GAP);
    *y = DOCK_Y + (DOCK_H - DOCK_ITEM) / 2;
}

/* returns the entry index under the pointer, or -1 */
static int hit_test(void)
{
    int i, x, y;

    if (cur_y < DOCK_Y || cur_y >= DOCK_Y + DOCK_H) return -1;
    for (i = 0; i < entry_count; i++) {
        dock_item_pos(i, &x, &y);
        if (cur_x >= x - 2 && cur_x < x + DOCK_ITEM + 2)
            return i;
    }
    return -1;
}

